import { describe, expect, it } from 'vitest';
import {
  AgentPrDescriptionGenerator, buildPrDescriptionPrompt, cleanGeneratedPrDescription,
  fallbackPrDescription, resolvePrDescription, type PrDescriptionContext,
} from '@main/domain/pr-description';

const context: PrDescriptionContext = {
  title: 'Fix login redirect loop',
  objectives: ['please fix the login loop, it bounces back to /login every time!!'],
  branch: 'conductor/abc',
  base: 'main',
  commits: ['Fix login redirect loop'],
  changedFiles: ['src/auth/session.ts', 'test/auth/session.test.ts'],
  diffStat: 'src/auth/session.ts | 10 +++++-----',
  diff: '@@ -1 +1 @@\n-redirect("/login")\n+redirect("/home")',
};

describe('buildPrDescriptionPrompt', () => {
  it('grounds the agent in the actual change and forbids copying the user prompt', () => {
    const prompt = buildPrDescriptionPrompt(context);
    expect(prompt).toContain('as the agent that made them');
    expect(prompt).toContain('Do not quote, copy, or restate the user request verbatim');
    expect(prompt).toContain('Never invent test results');
    expect(prompt).toContain('Fix login redirect loop');
    expect(prompt).toContain('src/auth/session.ts');
    expect(prompt).toContain('+redirect("/home")');
    expect(prompt).toContain('conductor/abc -> main');
  });

  it('truncates an oversized diff', () => {
    const prompt = buildPrDescriptionPrompt({ ...context, diff: 'x'.repeat(50_000) });
    expect(prompt).toContain('(diff truncated)');
    expect(prompt.length).toBeLessThan(20_000);
  });
});

describe('cleanGeneratedPrDescription', () => {
  it('strips a wrapping fence and preamble', () => {
    const raw = 'Here is the pull request description:\n\n```markdown\n## Summary\n\nFixes the loop.\n```';
    expect(cleanGeneratedPrDescription(raw)).toBe('## Summary\n\nFixes the loop.');
  });

  it('rejects empty text and the user prompt handed straight back', () => {
    expect(cleanGeneratedPrDescription('   ')).toBeUndefined();
    expect(cleanGeneratedPrDescription(context.objectives[0]!, context.objectives)).toBeUndefined();
  });
});

describe('fallbackPrDescription', () => {
  it('summarizes commits and files without ever using the raw prompt', () => {
    const body = fallbackPrDescription(context);
    expect(body).toContain('## Summary');
    expect(body).toContain('Fix login redirect loop');
    expect(body).toContain('`src/auth/session.ts`');
    expect(body).not.toContain('bounces back to /login');
  });
});

describe('resolvePrDescription', () => {
  it('uses the agent-written description when generation succeeds', async () => {
    const body = await resolvePrDescription(context, async () => '## Summary\n\nThe session redirect now lands on /home.');
    expect(body).toContain('lands on /home');
    expect(body).not.toContain('bounces back');
  });

  it('falls back to the change summary when generation fails, returns the prompt, or times out', async () => {
    const failed = await resolvePrDescription(context, async () => { throw new Error('agent unavailable'); });
    expect(failed).toContain('### Files changed');

    const parroted = await resolvePrDescription(context, async () => context.objectives[0]);
    expect(parroted).toContain('### Files changed');
    expect(parroted).not.toContain('bounces back');

    const slow = await resolvePrDescription(context, () => new Promise(() => undefined), 10);
    expect(slow).toContain('### Files changed');
  });
});

describe('AgentPrDescriptionGenerator', () => {
  it('sends the change-grounded prompt to the agent and cleans its reply', async () => {
    const seen: string[] = [];
    const generator = new AgentPrDescriptionGenerator(async (prompt) => {
      seen.push(prompt);
      return '```\n## Summary\n\nGenerated by the agent from the diff.\n```';
    });
    await expect(generator.generate(context)).resolves.toBe('## Summary\n\nGenerated by the agent from the diff.');
    expect(seen[0]).toContain('+redirect("/home")');
  });

  it('returns undefined when the agent yields nothing usable', async () => {
    const generator = new AgentPrDescriptionGenerator(async () => 'no');
    await expect(generator.generate(context)).resolves.toBeUndefined();
  });
});
